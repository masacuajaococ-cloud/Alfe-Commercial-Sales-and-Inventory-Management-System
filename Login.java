    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
         String username = jTextField1.getText().trim();
    String password = new String(jPasswordField1.getPassword());

    if (username.isEmpty() || password.isEmpty()) {
        javax.swing.JOptionPane.showMessageDialog(
            this,
            "Please enter your username and password.",
            "Login",
            javax.swing.JOptionPane.WARNING_MESSAGE
        );
        return;
    }

    String sql = "SELECT id, first_name, last_name, username, role "
               + "FROM users WHERE username = ? AND password = ?";

    DatabaseConnection db = new DatabaseConnection();
    
    javax.swing.JOptionPane.showMessageDialog(
    this,
    "Login successful!",
    "Welcome",
    javax.swing.JOptionPane.INFORMATION_MESSAGE
);

    try (
        java.sql.Connection conn = db.connect();
        java.sql.PreparedStatement pst = conn.prepareStatement(sql)
    ) {
        pst.setString(1, username);
        pst.setString(2, password);

        try (java.sql.ResultSet rs = pst.executeQuery()) {
            if (!rs.next()) {
                javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Invalid username or password.",
                    "Login Failed",
                    javax.swing.JOptionPane.ERROR_MESSAGE
                );
                return;
            }

            int userId = rs.getInt("id");
            String firstName = rs.getString("first_name");
            String lastName = rs.getString("last_name");
            String loggedUsername = rs.getString("username");

            String roleFromDatabase = rs.getString("role");
            String role = roleFromDatabase == null
                    ? ""
                    : roleFromDatabase.trim();

            if (!"admin".equalsIgnoreCase(role)
                    && !"cashier".equalsIgnoreCase(role)) {
                javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "This account has an unrecognized role: [" + role + "].",
                    "Access Denied",
                    javax.swing.JOptionPane.ERROR_MESSAGE
                );
                return;
            }

            Session.userId = userId;
            Session.firstName = firstName;
            Session.lastName = lastName;
            Session.username = loggedUsername;
            Session.role = role;

            System.out.println("LOGIN USER ID: " + Session.userId);
            System.out.println("LOGIN USERNAME: " + Session.username);
            System.out.println("LOGIN ROLE: [" + Session.role + "]");

            String historySQL =
                "INSERT INTO login_history (user_id, username, role) "
                + "VALUES (?, ?, ?)";

            try (java.sql.PreparedStatement historyStmt =
                    conn.prepareStatement(historySQL)) {

                historyStmt.setInt(1, userId);
                historyStmt.setString(2, loggedUsername);
                historyStmt.setString(3, role);
                historyStmt.executeUpdate();

            } catch (java.sql.SQLException historyError) {
                historyError.printStackTrace();

                javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Login history could not be recorded:\n"
                        + historyError.getMessage()
                        + "\n\nThe system will still attempt to open your dashboard.",
                    "Login History Warning",
                    javax.swing.JOptionPane.WARNING_MESSAGE
                );
            }

            try {
                if ("admin".equalsIgnoreCase(role)) {
                    System.out.println("Opening ADMIN dashboard...");

                    Dashboard dashboard = new Dashboard();
                    dashboard.setLocationRelativeTo(null);
                    dashboard.setVisible(true);
                    dashboard.toFront();

                    System.out.println("ADMIN dashboard displayed.");

                } else {
                    System.out.println("Opening CASHIER dashboard...");

                    CashierDashboard cashierDashboard =
                        new CashierDashboard();

                    cashierDashboard.setLocationRelativeTo(null);
                    cashierDashboard.setVisible(true);
                    cashierDashboard.toFront();

                    System.out.println("CASHIER dashboard displayed.");
                }

                this.dispose();

            } catch (Exception dashboardError) {
                dashboardError.printStackTrace();

                javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Could not open the "
                        + role + " dashboard:\n"
                        + dashboardError.getMessage()
                        + "\n\nCheck the NetBeans Output window for details.",
                    "Dashboard Error",
                    javax.swing.JOptionPane.ERROR_MESSAGE
                );
            }
        }

    } catch (java.sql.SQLException e) {
        e.printStackTrace();

        javax.swing.JOptionPane.showMessageDialog(
            this,
            "Database connection or login query failed:\n"
                + e.getMessage(),
            "Database Error",
            javax.swing.JOptionPane.ERROR_MESSAGE
        );
    }
    }//GEN-LAST:event_jButton2ActionPerformed

