private void displayCashierName() {
    String firstName = Session.firstName;
    String lastName = Session.lastName;

    if (firstName == null) {
        firstName = "";
    }

    if (lastName == null) {
        lastName = "";
    }

    String fullName = (firstName + " " + lastName).trim();

    if (fullName.isEmpty()) {
        jLabel3.setText(Session.username != null
                ? Session.username
                : "Cashier");
    } else {
        jLabel3.setText(fullName);
    }
}

