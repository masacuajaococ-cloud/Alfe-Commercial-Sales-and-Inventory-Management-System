    private void loadTransactions() {

    javax.swing.table.DefaultTableModel model =
        (javax.swing.table.DefaultTableModel) jTable1.getModel();

    model.setRowCount(0);

    String sql =
        "SELECT " +
        "s.transaction_id, " +
        "s.sale_date, " +
        "CONCAT(u.first_name, ' ', u.last_name) AS processed_by, " +
        "s.total_amount, " +
        "s.payment, " +
        "s.change_amount, " +
        "s.payment_method " +
        "FROM sales s " +
        "LEFT JOIN users u ON s.user_id = u.id " +
        "ORDER BY s.id DESC";

    DatabaseConnection db = new DatabaseConnection();

    try (
        java.sql.Connection conn = db.connect();
        java.sql.PreparedStatement pst =
            conn.prepareStatement(sql);
        java.sql.ResultSet rs =
            pst.executeQuery()
    ) {

        while (rs.next()) {

            String processedBy =
                rs.getString("processed_by");

            if (processedBy == null ||
                processedBy.trim().isEmpty()) {

                processedBy = "Unknown User";
            }

            model.addRow(new Object[] {

                rs.getString("transaction_id"),

                rs.getTimestamp("sale_date"),

                processedBy,

                "₱" + String.format(
                    "%.2f",
                    rs.getDouble("total_amount")
                ),

                "₱" + String.format(
                    "%.2f",
                    rs.getDouble("payment")
                ),

                "₱" + String.format(
                    "%.2f",
                    rs.getDouble("change_amount")
                ),

                rs.getString("payment_method")
            });
        }

    } catch (java.sql.SQLException e) {

        javax.swing.JOptionPane.showMessageDialog(
            this,
            "Failed to load transactions:\n" +
            e.getMessage(),
            "Database Error",
            javax.swing.JOptionPane.ERROR_MESSAGE
        );
    }
}

