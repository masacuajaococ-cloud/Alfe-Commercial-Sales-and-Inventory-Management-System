    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
String username = jTextField1.getText().trim();
    String recoveryCode = jTextField2.getText().trim();

    char[] newChars = jPasswordField2.getPassword();
    char[] confirmChars = jPasswordField3.getPassword();

    try {
        if (username.isEmpty() || recoveryCode.isEmpty()
                || newChars.length == 0 || confirmChars.length == 0) {
            JOptionPane.showMessageDialog(
                this, "Please fill in all fields.",
                "Missing Information", JOptionPane.WARNING_MESSAGE
            );
            return;
        }

        if (newChars.length < 8) {
            JOptionPane.showMessageDialog(
                this, "Password must be at least 8 characters.",
                "Invalid Password", JOptionPane.WARNING_MESSAGE
            );
            return;
        }

        if (!Arrays.equals(newChars, confirmChars)) {
            JOptionPane.showMessageDialog(
                this, "Passwords do not match.",
                "Invalid Password", JOptionPane.WARNING_MESSAGE
            );
            return;
        }

        String enteredHash = hashRecoveryCode(recoveryCode);
        DatabaseConnection db = new DatabaseConnection();

        try (Connection conn = db.connect()) {
            String checkSql =
                "SELECT recovery_code_hash "
                + "FROM password_recovery WHERE role = 'Admin'";

            boolean validCode = false;

            try (PreparedStatement checkStmt =
                    conn.prepareStatement(checkSql);
                 ResultSet rs = checkStmt.executeQuery()) {

                if (rs.next()) {
                    String storedHash =
                        rs.getString("recovery_code_hash");

                    validCode = storedHash != null
                        && MessageDigest.isEqual(
                            enteredHash.getBytes(StandardCharsets.UTF_8),
                            storedHash.toLowerCase(
                                java.util.Locale.ROOT
                            ).getBytes(StandardCharsets.UTF_8)
                        );
                }
            }

            if (!validCode) {
                JOptionPane.showMessageDialog(
                    this, "Invalid recovery code.",
                    "Recovery Failed", JOptionPane.ERROR_MESSAGE
                );
                return;
            }

            String sql =
                "UPDATE users SET password = ? "
                + "WHERE username = ? AND role = 'Admin'";

            try (PreparedStatement stmt = conn.prepareStatement(sql)) {
                stmt.setString(1, new String(newChars));
                stmt.setString(2, username);

                int updated = stmt.executeUpdate();

                if (updated == 1) {
                    JOptionPane.showMessageDialog(
                        this, "Admin password reset successfully!",
                        "Success", JOptionPane.INFORMATION_MESSAGE
                    );

                    jTextField1.setText("");
                    jTextField2.setText("");
                    jPasswordField2.setText("");
                    jPasswordField3.setText("");

                    Window window = SwingUtilities.getWindowAncestor(this);
                    if (window != null) {
                        window.dispose();
                    }
                } else {
                    JOptionPane.showMessageDialog(
                        this, "Admin username not found.",
                        "Reset Failed", JOptionPane.ERROR_MESSAGE
                    );
                }
            }
        }

    } catch (SQLException
            | java.security.NoSuchAlgorithmException e) {
        JOptionPane.showMessageDialog(
            this,
            "Unable to complete password reset. Please try again.",
            "Error", JOptionPane.ERROR_MESSAGE
        );
        e.printStackTrace();

    } finally {
        Arrays.fill(newChars, '\0');
        Arrays.fill(confirmChars, '\0');
    }
    }//GEN-LAST:event_jButton2ActionPerformed

