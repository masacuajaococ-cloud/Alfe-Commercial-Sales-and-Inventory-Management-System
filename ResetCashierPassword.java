private void loadCashiers() {
    jComboBox1.removeAllItems();
    jComboBox1.addItem("Select Cashier");
    cashierIds.clear();

    String sql = "SELECT id, first_name, last_name, username "
               + "FROM users WHERE role = 'Cashier' "
               + "ORDER BY first_name, last_name";

    try (
        Connection conn = new DatabaseConnection().connect();
        PreparedStatement pst = conn.prepareStatement(sql);
        ResultSet rs = pst.executeQuery()
    ) {
        while (rs.next()) {
            int id = rs.getInt("id");

            String displayName = rs.getString("first_name") + " "
                    + rs.getString("last_name") + " ("
                    + rs.getString("username") + ")";

            jComboBox1.addItem(displayName);
            cashierIds.put(displayName, id);
        }
    } catch (SQLException e) {
        JOptionPane.showMessageDialog(
            this,
            "Unable to load cashier accounts:\n" + e.getMessage(),
            "Database Error",
            JOptionPane.ERROR_MESSAGE
        );
    }
}

