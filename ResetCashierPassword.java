    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        if (Session.userId <= 0 ||
        Session.role == null ||
        !Session.role.equalsIgnoreCase("Admin")) {

        JOptionPane.showMessageDialog(
            this,
            "Access denied. Only administrators can reset cashier passwords.",
            "Permission Denied",
            JOptionPane.ERROR_MESSAGE
        );
        return;
    }

    String selected = (String) jComboBox1.getSelectedItem();

    if (selected == null || !cashierIds.containsKey(selected)) {
        JOptionPane.showMessageDialog(
            this,
            "Please select a cashier.",
            "Missing Information",
            JOptionPane.WARNING_MESSAGE
        );
        return;
    }

    int cashierId = cashierIds.get(selected);

    char[] newChars = jPasswordField2.getPassword();
    char[] confirmChars = jPasswordField3.getPassword();

    try {
        if (newChars.length == 0 || confirmChars.length == 0) {
            JOptionPane.showMessageDialog(
                this,
                "Please fill in both password fields.",
                "Missing Information",
                JOptionPane.WARNING_MESSAGE
            );
            return;
        }

        if (!Arrays.equals(newChars, confirmChars)) {
            JOptionPane.showMessageDialog(
                this,
                "Passwords do not match.",
                "Password Error",
                JOptionPane.WARNING_MESSAGE
            );
            return;
        }

        if (newChars.length < 8) {
            JOptionPane.showMessageDialog(
                this,
                "Password must contain at least 8 characters.",
                "Password Error",
                JOptionPane.WARNING_MESSAGE
            );
            return;
        }

        int confirm = JOptionPane.showConfirmDialog(
            this,
            "Reset the password for " + selected + "?",
            "Confirm Password Reset",
            JOptionPane.YES_NO_OPTION,
            JOptionPane.WARNING_MESSAGE
        );

        if (confirm != JOptionPane.YES_OPTION) {
            return;
        }

        String sql = "UPDATE users SET password = ? "
                   + "WHERE id = ? AND role = 'Cashier'";

        try (
            Connection conn = new DatabaseConnection().connect();
            PreparedStatement pst = conn.prepareStatement(sql)
        ) {
            pst.setString(1, new String(newChars));
            pst.setInt(2, cashierId);

            int updated = pst.executeUpdate();

            if (updated == 1) {
                JOptionPane.showMessageDialog(
                    this,
                    "Cashier password reset successfully!",
                    "Success",
                    JOptionPane.INFORMATION_MESSAGE
                );

                jPasswordField2.setText("");
                jPasswordField3.setText("");

            } else {
                JOptionPane.showMessageDialog(
                    this,
                    "The cashier account was not found or is no longer a cashier.",
                    "Reset Failed",
                    JOptionPane.ERROR_MESSAGE
                );

                loadCashiers();
            }
        }

    } catch (SQLException e) {
        JOptionPane.showMessageDialog(
            this,
            "Database error:\n" + e.getMessage(),
            "Database Error",
            JOptionPane.ERROR_MESSAGE
        );

    } finally {
        Arrays.fill(newChars, '\0');
        Arrays.fill(confirmChars, '\0');
    }
    }//GEN-LAST:event_jButton2ActionPerformed

