      private void performSearch(boolean showMessages) {

    String dateText = jTextField1.getText().trim();
    String transactionId = jTextField2.getText().trim();

    String selectedPayment =
        jComboBox1.getSelectedItem().toString();

    // Ignore placeholders
    if (dateText.equals("MM/DD/YYYY")) {
        dateText = "";
    }

    if (transactionId.equals("Search transactions...")) {
        transactionId = "";
    }

    // If there are no filters, load all transactions
    if (dateText.isEmpty()
            && transactionId.isEmpty()
            && selectedPayment.equals("All Payments")) {

        loadTransactions();
        return;
    }

    // Validate date
    if (!dateText.isEmpty()) {

        try {

            java.text.SimpleDateFormat sdf =
                new java.text.SimpleDateFormat("MM/dd/yyyy");

            sdf.setLenient(false);
            sdf.parse(dateText);

        } catch (java.text.ParseException e) {

            // Only show error when Search button is clicked
            if (showMessages) {

                javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Please enter a valid date.\nExample: 09/30/2026",
                    "Invalid Date",
                    javax.swing.JOptionPane.WARNING_MESSAGE
                );
            }

            return;
        }
    }

    javax.swing.table.DefaultTableModel model =
        (javax.swing.table.DefaultTableModel) jTable1.getModel();

    model.setRowCount(0);

    StringBuilder sql = new StringBuilder(
        "SELECT " +
        "transaction_id, " +
        "sale_date, " +
        "total_amount, " +
        "payment, " +
        "change_amount, " +
        "payment_method " +
        "FROM sales " +
        "WHERE user_id = ?"
    );

    java.util.ArrayList<String> parameters =
        new java.util.ArrayList<>();

    // Search bar keyword
    if (!transactionId.isEmpty()) {

        sql.append(
            " AND (" +
            "transaction_id LIKE ? " +
            "OR payment_method LIKE ? " +
            "OR CAST(total_amount AS CHAR) LIKE ? " +
            "OR CAST(payment AS CHAR) LIKE ? " +
            "OR CAST(change_amount AS CHAR) LIKE ?" +
            ")"
        );

        String keyword = "%" + transactionId + "%";

        parameters.add(keyword);
        parameters.add(keyword);
        parameters.add(keyword);
        parameters.add(keyword);
        parameters.add(keyword);
    }

    // Date filter
    if (!dateText.isEmpty()) {

        sql.append(
            " AND DATE_FORMAT(sale_date, '%m/%d/%Y') = ?"
        );

        parameters.add(dateText);
    }

    // Payment method filter
    if (!selectedPayment.equals("All Payments")) {

        sql.append(
            " AND payment_method = ?"
        );

        parameters.add(selectedPayment);
    }

    sql.append(" ORDER BY id DESC");

    DatabaseConnection db = new DatabaseConnection();

    try (
        java.sql.Connection conn = db.connect();
        java.sql.PreparedStatement pst =
            conn.prepareStatement(sql.toString())
    ) {

        // First parameter = logged-in cashier
        pst.setInt(1, Session.userId);

        // Remaining parameters = search filters
        for (int i = 0; i < parameters.size(); i++) {

            pst.setString(
                i + 2,
                parameters.get(i)
            );
        }

        java.sql.ResultSet rs =
            pst.executeQuery();

        boolean found = false;

        while (rs.next()) {

            found = true;

            model.addRow(new Object[] {

                rs.getString("transaction_id"),

                rs.getTimestamp("sale_date"),

                "₱" + String.format(
                    "%.2f",
                    rs.getDouble("total_amount")
                ),

                "₱" + String.format(
                    "%.2f",
                    rs.getDouble("payment")
                ),

                "₱" + String.format(
                    "%.2f",
                    rs.getDouble("change_amount")
                ),

                rs.getString("payment_method")
            });
        }

        // Only show popup when Search button was clicked
        if (!found && showMessages) {

            javax.swing.JOptionPane.showMessageDialog(
                this,
                "No transactions found matching your filters.",
                "Search",
                javax.swing.JOptionPane.INFORMATION_MESSAGE
            );
        }

    } catch (java.sql.SQLException e) {

        javax.swing.JOptionPane.showMessageDialog(
            this,
            "Search failed:\n" + e.getMessage(),
            "Database Error",
            javax.swing.JOptionPane.ERROR_MESSAGE
        );
    }
}
