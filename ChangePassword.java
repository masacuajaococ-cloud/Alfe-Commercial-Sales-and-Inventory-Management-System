    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        char[] currentChars = jPasswordField1.getPassword();
    char[] newChars = jPasswordField2.getPassword();
    char[] confirmChars = jPasswordField3.getPassword();

    try {
        // Check whether a user is logged in
        if (Session.userId <= 0) {
            JOptionPane.showMessageDialog(
                this,
                "No logged-in user was found. Please log in again.",
                "Session Error",
                JOptionPane.ERROR_MESSAGE
            );
            return;
        }

        // Check for empty fields
        if (currentChars.length == 0 ||
            newChars.length == 0 ||
            confirmChars.length == 0) {

            JOptionPane.showMessageDialog(
                this,
                "Please fill in all password fields.",
                "Missing Information",
                JOptionPane.WARNING_MESSAGE
            );
            return;
        }

        // Check whether the new password and confirmation match
        if (!Arrays.equals(newChars, confirmChars)) {
            JOptionPane.showMessageDialog(
                this,
                "New password and confirmation do not match.",
                "Password Error",
                JOptionPane.WARNING_MESSAGE
            );
            return;
        }

        // Prevent using the current password again
        if (Arrays.equals(currentChars, newChars)) {
            JOptionPane.showMessageDialog(
                this,
                "Your new password must be different from your current password.",
                "Password Error",
                JOptionPane.WARNING_MESSAGE
            );
            return;
        }

        String currentPassword = new String(currentChars);
        String newPassword = new String(newChars);

        String checkSQL =
            "SELECT password FROM users WHERE id = ?";

        String updateSQL =
            "UPDATE users SET password = ? WHERE id = ? AND password = ?";

        DatabaseConnection db = new DatabaseConnection();

        try (Connection conn = db.connect()) {

            // Verify the current password
            try (PreparedStatement checkStmt =
                    conn.prepareStatement(checkSQL)) {

                checkStmt.setInt(1, Session.userId);

                try (ResultSet rs = checkStmt.executeQuery()) {

                    if (!rs.next() ||
                        !currentPassword.equals(rs.getString("password"))) {

                        JOptionPane.showMessageDialog(
                            this,
                            "Your current password is incorrect.",
                            "Password Error",
                            JOptionPane.ERROR_MESSAGE
                        );
                        return;
                    }
                }
            }

            // Update the password
            try (PreparedStatement updateStmt =
                    conn.prepareStatement(updateSQL)) {

                updateStmt.setString(1, newPassword);
                updateStmt.setInt(2, Session.userId);
                updateStmt.setString(3, currentPassword);

                int rowsUpdated = updateStmt.executeUpdate();

                if (rowsUpdated > 0) {
                    JOptionPane.showMessageDialog(
                        this,
                        "Password changed successfully!",
                        "Success",
                        JOptionPane.INFORMATION_MESSAGE
                    );

                    jPasswordField1.setText("");
                    jPasswordField2.setText("");
                    jPasswordField3.setText("");

                    dispose();

                } else {
                    JOptionPane.showMessageDialog(
                        this,
                        "Password was not changed. Please try again.",
                        "Update Failed",
                        JOptionPane.ERROR_MESSAGE
                    );
                }
            }
        }

    } catch (SQLException e) {
        JOptionPane.showMessageDialog(
            this,
            "Database error:\n" + e.getMessage(),
            "Database Error",
            JOptionPane.ERROR_MESSAGE
        );

    } finally {
        Arrays.fill(currentChars, '\0');
        Arrays.fill(newChars, '\0');
        Arrays.fill(confirmChars, '\0');
    }
    }//GEN-LAST:event_jButton2ActionPerformed

